pub fn get_runtime_class_proto(name: &str) -> Option<RuntimeClassProto> {
    let index = RUNTIME_CLASSES.binary_search_by_key(&name, |&(registered, _)| registered).ok()?;
    Some(RUNTIME_CLASSES[index].1())
}

struct JavaRuntimeBootstrapClassLoader {
    runtime: Box<dyn Runtime>,
}

#[async_trait::async_trait]
impl BootstrapClassLoader for JavaRuntimeBootstrapClassLoader {
    async fn load_class(&self, jvm: &Jvm, name: &str) -> Result<Option<Box<dyn ClassDefinition>>> {
        if let Some(element_type_name) = name.strip_prefix('[') {
            return Ok(Some(self.runtime.define_array_class(jvm, element_type_name).await?));
        }

        self.runtime.find_rustjar_class(jvm, RT_RUSTJAR, name).await
    }
}

pub fn get_bootstrap_class_loader(runtime: Box<dyn Runtime>) -> impl BootstrapClassLoader {
    JavaRuntimeBootstrapClassLoader { runtime }
}

#[cfg(test)]
mod tests {
    use super::{RUNTIME_CLASSES, get_runtime_class_proto};

    #[test]
    fn runtime_classes_are_sorted_and_resolve_by_their_declared_names() {
        assert!(RUNTIME_CLASSES.windows(2).all(|pair| pair[0].0 < pair[1].0));
        for &(name, _) in RUNTIME_CLASSES {
            assert_eq!(get_runtime_class_proto(name).unwrap().name, name);
        }
    }
}
